const I18nContext = createContext({ lang: "it", t: (k) => k, setLang: () => {} });

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    const saved = typeof window !== "undefined" ? localStorage.getItem("pm_lang") : null;
    if (saved && dict[saved]) return saved;
    const browser = typeof navigator !== "undefined" ? navigator.language?.slice(0, 2) : "it";
    return dict[browser] ? browser : "it";
  });

  useEffect(() => {
    if (typeof window !== "undefined") localStorage.setItem("pm_lang", lang);
    if (typeof document !== "undefined") document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((l) => {
    if (dict[l]) setLangState(l);
  }, []);

  const t = useCallback((key) => {
    return (dict[lang] && dict[lang][key]) || dict.en[key] || key;
  }, [lang]);

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
